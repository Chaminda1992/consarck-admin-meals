create policy "orders read" on public.orders for select using (true);
create policy "orders insert" on public.orders for insert with check (true);
create policy "orders update" on public.orders for update using (true);
create policy "orders delete" on public.orders for delete using (true);

create policy "settings read" on public.company_settings for select using (true);
create policy "settings insert" on public.company_settings for insert with check (true);
create policy "settings update" on public.company_settings for update using (true);

create policy "admin read" on public.admin_profiles for select using (true);

