create table if not exists public.employees (
 id bigint generated by default as identity primary key,
 employee_no text unique not null,
 name text not null,
 department text,
 phone text,
 pin text not null,
 active boolean default true,
 created_at timestamptz default now()
);

create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 employee_id bigint not null references public.employees(id) on delete cascade,
 order_date date not null,
 breakfast boolean default false,
 lunch boolean default false,
 dinner boolean default false,
 quantity integer not null default 1 check(quantity > 0),
 delivery boolean default false,
 status text default 'submitted',
 created_at timestamptz default now()
);

create table if not exists public.company_settings (
 id bigint generated by default as identity primary key,
 company_name text default 'Consarck Pvt Ltd',
 address text default 'Kuliyapitiya, Weralugama',
 phone text default '0763590747',
 email text,
 website text,
 logo_url text,
 meal_type text default 'Rice and Curry',
 order_closing_time time default '09:00'
);

create table if not exists public.admin_profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text,
 role text default 'admin'
);

alter table public.employees enable row level security;
alter table public.orders enable row level security;
alter table public.company_settings enable row level security;
alter table public.admin_profiles enable row level security;

-- For a first prototype. Tighten these policies before public production deployment.
create policy "employees read" on public.employees for select using (true);
